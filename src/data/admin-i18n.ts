/** Replaces `{name}` placeholders. Missing values are left as-is so gaps are visible. */
export function formatTranslation(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;

  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in vars ? String(vars[key]) : match,
  );
}
